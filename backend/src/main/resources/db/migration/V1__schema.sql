-- ReturnRight schema (Part 1 §6.3; ADR-002: text + CHECK instead of native enums).
-- [BR-nn] marks constraints that enforce business rules in the database.

-- ---------- Reference & orders ----------
CREATE TABLE categories (
  id                 smallint PRIMARY KEY,
  code               text NOT NULL UNIQUE,
  name               text NOT NULL,
  is_returnable      boolean NOT NULL,
  return_window_days smallint,
  CONSTRAINT ck_categories_window CHECK (                     -- [BR-1]
      (NOT is_returnable AND return_window_days IS NULL)
   OR (is_returnable AND return_window_days BETWEEN 1 AND 365))
);

CREATE TABLE products (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku         text NOT NULL UNIQUE,
  name        text NOT NULL,
  brand       text NOT NULL,
  category_id smallint NOT NULL REFERENCES categories(id),
  price_paise bigint NOT NULL CONSTRAINT ck_products_price CHECK (price_paise > 0)
);
CREATE INDEX ix_products_category ON products(category_id);

CREATE TABLE customers (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email         text NOT NULL,
  full_name     text NOT NULL,
  phone         text,
  address_line1 text NOT NULL,
  city          text NOT NULL,
  state         text NOT NULL,
  pincode       text NOT NULL,
  is_flagged    boolean NOT NULL DEFAULT false,
  flagged_at    timestamptz,
  flag_reason   text,
  created_at    timestamptz NOT NULL,
  CONSTRAINT ck_customers_flag CHECK (is_flagged = (flagged_at IS NOT NULL))
);
CREATE UNIQUE INDEX uq_customers_email_ci ON customers (lower(email));

CREATE TABLE orders (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_number      text NOT NULL UNIQUE,
  customer_id       bigint NOT NULL REFERENCES customers(id),
  status            text NOT NULL CONSTRAINT ck_orders_status CHECK (status IN ('PLACED','SHIPPED','DELIVERED','CANCELLED')),
  payment_method    text NOT NULL CONSTRAINT ck_orders_payment CHECK (payment_method IN ('CARD','UPI','NETBANKING','WALLET')), -- [A-23]
  payment_reference text NOT NULL UNIQUE,
  placed_at         timestamptz NOT NULL,
  delivered_at      timestamptz,
  total_paise       bigint NOT NULL CONSTRAINT ck_orders_total CHECK (total_paise > 0),
  CONSTRAINT ck_orders_delivered CHECK ((status = 'DELIVERED') = (delivered_at IS NOT NULL)),  -- [BR-2] [A-01]
  CONSTRAINT ck_orders_dates CHECK (delivered_at IS NULL OR delivered_at >= placed_at)
);
CREATE INDEX ix_orders_customer ON orders(customer_id, placed_at DESC);

CREATE TABLE order_items (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id         bigint NOT NULL REFERENCES orders(id),
  line_no          smallint NOT NULL,
  product_id       bigint NOT NULL REFERENCES products(id),
  quantity         smallint NOT NULL CONSTRAINT ck_order_items_qty CHECK (quantity BETWEEN 1 AND 10),
  unit_price_paise bigint NOT NULL CONSTRAINT ck_order_items_price CHECK (unit_price_paise > 0),  -- [A-11]
  CONSTRAINT uq_order_items_line UNIQUE (order_id, line_no)
);
CREATE INDEX ix_order_items_order ON order_items(order_id);

-- ---------- Staff ----------
CREATE TABLE users (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      text NOT NULL UNIQUE,
  display_name  text NOT NULL,
  email         text NOT NULL,
  password_hash text NOT NULL,
  role          text NOT NULL CONSTRAINT ck_users_role CHECK (role IN ('WAREHOUSE_AGENT','FINANCE_REVIEWER','OPS_MANAGER','ADMIN')),
  is_active     boolean NOT NULL DEFAULT true,
  created_at    timestamptz NOT NULL,
  last_login_at timestamptz
);

-- ---------- Returns ----------
CREATE SEQUENCE rma_seq START 1000;

CREATE TABLE returns (
  id                      uuid PRIMARY KEY,
  rma_number              text NOT NULL UNIQUE,
  order_id                bigint NOT NULL REFERENCES orders(id),
  customer_id             bigint NOT NULL REFERENCES customers(id),
  status                  text NOT NULL CONSTRAINT ck_returns_status CHECK (status IN (
                            'REQUESTED','APPROVED','IN_TRANSIT','RECEIVED','INSPECTED','PENDING_FINANCE',
                            'REFUND_PENDING','REFUND_FAILED','REFUNDED','REJECTED','CANCELLED')),
  refund_method           text NOT NULL CONSTRAINT ck_returns_method CHECK (refund_method IN ('ORIGINAL_PAYMENT','STORE_CREDIT')),
  version                 integer NOT NULL DEFAULT 1,
  approved_refund_paise   bigint CONSTRAINT ck_returns_amount_nonneg CHECK (approved_refund_paise >= 0),
  outcome                 text CONSTRAINT ck_returns_outcome CHECK (outcome IN ('FULL','PARTIAL','NONE')),
  requires_finance_review boolean NOT NULL DEFAULT false,
  finance_review_reason   text CONSTRAINT ck_returns_frr CHECK (finance_review_reason IN ('AMOUNT','FLAGGED','BOTH')),
  cancel_reason           text CONSTRAINT ck_returns_cancel CHECK (cancel_reason IN ('CUSTOMER','LABEL_EXPIRED','OPS')),
  created_at              timestamptz NOT NULL,
  updated_at              timestamptz NOT NULL,
  closed_at               timestamptz,
  CONSTRAINT ck_returns_amount_after_inspection CHECK (                         -- [BR-3]
      status IN ('REQUESTED','APPROVED','IN_TRANSIT','RECEIVED','CANCELLED') OR approved_refund_paise IS NOT NULL),
  CONSTRAINT ck_returns_refunded_positive CHECK (status <> 'REFUNDED' OR approved_refund_paise > 0),
  CONSTRAINT ck_returns_finance_threshold CHECK (                               -- [BR-4]
      approved_refund_paise IS NULL OR approved_refund_paise <= 1000000 OR requires_finance_review),
  CONSTRAINT ck_returns_cancel_reason CHECK ((status = 'CANCELLED') = (cancel_reason IS NOT NULL)),
  CONSTRAINT ck_returns_terminal_closed CHECK ((status IN ('REFUNDED','REJECTED','CANCELLED')) = (closed_at IS NOT NULL))
);
CREATE INDEX ix_returns_customer_created ON returns(customer_id, created_at);    -- [BR-5]
CREATE INDEX ix_returns_open_status ON returns(status) WHERE closed_at IS NULL;
CREATE INDEX ix_returns_order ON returns(order_id);

CREATE TABLE return_items (
  id                   uuid PRIMARY KEY,
  return_id            uuid NOT NULL REFERENCES returns(id),
  order_item_id        bigint NOT NULL REFERENCES order_items(id),
  unit_index           smallint NOT NULL CONSTRAINT ck_ri_unit CHECK (unit_index >= 1),
  status               text NOT NULL CONSTRAINT ck_ri_status CHECK (status IN ('REQUESTED','RECEIVED','ACCEPTED','REJECTED','REFUNDED','CANCELLED')),
  reason               text NOT NULL CONSTRAINT ck_ri_reason CHECK (reason IN (
                         'DAMAGED','DEFECTIVE','WRONG_ITEM','SIZE_FIT','NOT_AS_DESCRIBED','CHANGED_MIND','LATE_DELIVERY','OTHER')),
  reason_note          text CONSTRAINT ck_ri_note CHECK (char_length(reason_note) <= 500),
  unit_price_paise     bigint NOT NULL CONSTRAINT ck_ri_price CHECK (unit_price_paise > 0),
  eligibility_snapshot jsonb NOT NULL,
  grade                text CONSTRAINT ck_ri_grade CHECK (grade IN ('A','B','C')),
  decision             text CONSTRAINT ck_ri_decision CHECK (decision IN ('ACCEPT','REJECT')),
  reject_reason        text CONSTRAINT ck_ri_reject CHECK (reject_reason IN (
                         'NOT_IN_PARCEL','WRONG_ITEM_RETURNED','USED_OR_DAMAGED_BY_CUSTOMER','MISSING_PARTS','FINANCE_REJECTED')),
  refund_paise         bigint,
  inspection_notes     text CONSTRAINT ck_ri_notes CHECK (char_length(inspection_notes) <= 1000),
  inspected_by         bigint REFERENCES users(id),
  inspected_at         timestamptz,
  CONSTRAINT ck_ri_accept_needs_grade CHECK (decision <> 'ACCEPT' OR grade IS NOT NULL),
  CONSTRAINT ck_ri_reject_needs_reason CHECK (decision <> 'REJECT' OR reject_reason IS NOT NULL),
  CONSTRAINT ck_ri_grade_refund CHECK (                                        -- [BR-7]
      (decision IS NULL AND refund_paise IS NULL)
   OR (decision = 'REJECT' AND refund_paise = 0)
   OR (decision = 'ACCEPT' AND refund_paise =
        CASE WHEN grade = 'C' THEN (unit_price_paise + 1) / 2 ELSE unit_price_paise END)),
  CONSTRAINT ck_ri_status_decision CHECK (
      (status IN ('ACCEPTED','REFUNDED') AND decision = 'ACCEPT')
   OR (status = 'REJECTED' AND decision = 'REJECT')
   OR (status IN ('REQUESTED','RECEIVED','CANCELLED') AND decision IS NULL))
);
CREATE UNIQUE INDEX uq_return_items_active_unit                                -- [BR-8]
  ON return_items(order_item_id, unit_index) WHERE status <> 'CANCELLED';
CREATE INDEX ix_return_items_return ON return_items(return_id);

CREATE TABLE return_labels (
  id              uuid PRIMARY KEY,
  return_id       uuid NOT NULL REFERENCES returns(id),
  qr_token        text NOT NULL UNIQUE,
  tracking_number text NOT NULL UNIQUE,
  status          text NOT NULL CONSTRAINT ck_label_status CHECK (status IN ('ACTIVE','USED','VOIDED','EXPIRED')),
  issued_at       timestamptz NOT NULL,
  expires_at      timestamptz NOT NULL,
  used_at         timestamptz,
  CONSTRAINT ck_label_expiry CHECK (expires_at > issued_at),
  CONSTRAINT ck_label_used CHECK ((status = 'USED') = (used_at IS NOT NULL))
);
CREATE UNIQUE INDEX uq_label_one_active ON return_labels(return_id) WHERE status = 'ACTIVE';
CREATE INDEX ix_return_labels_return ON return_labels(return_id);

-- ---------- Finance ----------
CREATE TABLE finance_reviews (
  id                    uuid PRIMARY KEY,
  return_id             uuid NOT NULL REFERENCES returns(id),
  reviewer_id           bigint NOT NULL REFERENCES users(id),
  decision              text NOT NULL CONSTRAINT ck_fr_decision CHECK (decision IN ('APPROVED','REJECTED')),
  amount_paise_reviewed bigint NOT NULL CONSTRAINT ck_fr_amount CHECK (amount_paise_reviewed >= 0),
  note                  text,
  decided_at            timestamptz NOT NULL,
  CONSTRAINT uq_finance_reviews_return UNIQUE (return_id),                      -- [BR-10]
  CONSTRAINT ck_fr_reject_note CHECK (decision = 'APPROVED' OR note IS NOT NULL)
);

-- ---------- Refunds (ADR-001) ----------
CREATE TABLE refunds (
  id           uuid PRIMARY KEY,
  return_id    uuid NOT NULL REFERENCES returns(id),
  customer_id  bigint NOT NULL REFERENCES customers(id),
  amount_paise bigint NOT NULL CONSTRAINT ck_refunds_amount CHECK (amount_paise > 0),
  status       text NOT NULL CONSTRAINT ck_refunds_status CHECK (status IN ('PENDING','SUCCEEDED','FAILED')),
  created_at   timestamptz NOT NULL,
  completed_at timestamptz,
  CONSTRAINT uq_refunds_return UNIQUE (return_id)                               -- [BR-11]
);

CREATE TABLE refund_items (
  refund_id      uuid NOT NULL REFERENCES refunds(id),
  return_item_id uuid NOT NULL REFERENCES return_items(id),
  amount_paise   bigint NOT NULL CONSTRAINT ck_refund_items_amount CHECK (amount_paise > 0),
  PRIMARY KEY (refund_id, return_item_id),
  CONSTRAINT uq_refund_items_return_item UNIQUE (return_item_id)                -- [BR-12]
);

CREATE TABLE refund_attempts (
  id                      uuid PRIMARY KEY,
  refund_id               uuid NOT NULL REFERENCES refunds(id),
  attempt_no              smallint NOT NULL CONSTRAINT ck_ra_no CHECK (attempt_no >= 1),
  method                  text NOT NULL CONSTRAINT ck_ra_method CHECK (method IN ('ORIGINAL_PAYMENT','STORE_CREDIT')),
  gateway_idempotency_key text NOT NULL,
  status                  text NOT NULL CONSTRAINT ck_ra_status CHECK (status IN ('PENDING','SUCCEEDED','FAILED','UNKNOWN')),
  gateway_refund_id       text,
  decline_code            text,
  created_at              timestamptz NOT NULL,
  request_sent_at         timestamptz,
  last_checked_at         timestamptz,
  check_count             integer NOT NULL DEFAULT 0,
  completed_at            timestamptz,
  CONSTRAINT uq_ra_gateway_key UNIQUE (gateway_idempotency_key),                -- [BR-14]
  CONSTRAINT uq_ra_gateway_refund UNIQUE (gateway_refund_id),
  CONSTRAINT uq_ra_refund_attempt_no UNIQUE (refund_id, attempt_no),
  CONSTRAINT ck_ra_store_credit_no_gateway CHECK (method = 'ORIGINAL_PAYMENT' OR gateway_refund_id IS NULL),
  CONSTRAINT ck_ra_failed_has_code CHECK (status <> 'FAILED' OR decline_code IS NOT NULL)
);
CREATE UNIQUE INDEX uq_refund_one_live_attempt                                 -- [BR-15]
  ON refund_attempts(refund_id) WHERE status IN ('PENDING','UNKNOWN','SUCCEEDED');
CREATE INDEX ix_ra_reconcile ON refund_attempts(status, created_at) WHERE status IN ('PENDING','UNKNOWN');

-- ---------- Ledger (Part 1 §7) ----------
CREATE TABLE ledger_accounts (
  code        text PRIMARY KEY,
  name        text NOT NULL,
  normal_side text NOT NULL CONSTRAINT ck_la_side CHECK (normal_side IN ('DEBIT','CREDIT'))
);

CREATE TABLE ledger_transactions (
  id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  txn_type                text NOT NULL CONSTRAINT ck_lt_type CHECK (txn_type IN ('REFUND_ORIGINAL','REFUND_STORE_CREDIT','REVERSAL')),
  return_id               uuid NOT NULL REFERENCES returns(id),
  refund_attempt_id       uuid REFERENCES refund_attempts(id),
  reverses_transaction_id bigint REFERENCES ledger_transactions(id),
  memo                    text NOT NULL,
  correlation_id          text NOT NULL,
  posted_at               timestamptz NOT NULL,
  posted_by_actor         text NOT NULL,
  CONSTRAINT uq_lt_attempt UNIQUE (refund_attempt_id),                         -- [BR-16]
  CONSTRAINT uq_lt_reverses UNIQUE (reverses_transaction_id),                  -- [BR-17]
  CONSTRAINT ck_lt_shape CHECK (
      ((txn_type = 'REVERSAL') = (reverses_transaction_id IS NOT NULL))
  AND (txn_type = 'REVERSAL' OR refund_attempt_id IS NOT NULL))
);
CREATE INDEX ix_lt_return ON ledger_transactions(return_id);

CREATE TABLE ledger_entries (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transaction_id bigint NOT NULL REFERENCES ledger_transactions(id),
  account_code   text NOT NULL REFERENCES ledger_accounts(code),
  direction      text NOT NULL CONSTRAINT ck_le_direction CHECK (direction IN ('DEBIT','CREDIT')),
  amount_paise   bigint NOT NULL CONSTRAINT ck_le_amount CHECK (amount_paise > 0),
  customer_id    bigint REFERENCES customers(id),
  return_item_id uuid REFERENCES return_items(id),
  CONSTRAINT ck_le_store_credit_customer CHECK (account_code <> 'STORE_CREDIT_LIABILITY' OR customer_id IS NOT NULL)
);
CREATE INDEX ix_le_txn ON ledger_entries(transaction_id);
CREATE INDEX ix_le_account_customer ON ledger_entries(account_code, customer_id);

-- ---------- Cross-cutting ----------
CREATE TABLE audit_log (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  occurred_at    timestamptz NOT NULL,
  correlation_id text NOT NULL,
  actor_type     text NOT NULL CONSTRAINT ck_audit_actor CHECK (actor_type IN ('CUSTOMER','STAFF','SYSTEM')),
  actor_id       text NOT NULL,
  actor_role     text NOT NULL,
  entity_type    text NOT NULL,
  entity_id      text NOT NULL,
  event          text NOT NULL,
  from_state     text,
  to_state       text,
  before_data    jsonb,
  after_data     jsonb,
  metadata       jsonb NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX ix_audit_entity ON audit_log(entity_type, entity_id, occurred_at);
CREATE INDEX ix_audit_correlation ON audit_log(correlation_id);
CREATE INDEX ix_audit_occurred ON audit_log(occurred_at DESC);

CREATE TABLE notifications (
  id          uuid PRIMARY KEY,
  customer_id bigint NOT NULL REFERENCES customers(id),
  return_id   uuid REFERENCES returns(id),
  template    text NOT NULL,
  title       text NOT NULL,
  body        text NOT NULL,
  created_at  timestamptz NOT NULL,
  read_at     timestamptz
);
CREATE INDEX ix_notifications_customer ON notifications(customer_id, created_at DESC);

CREATE TABLE idempotency_keys (
  scope           text NOT NULL,
  idem_key        text NOT NULL CONSTRAINT ck_idem_key CHECK (char_length(idem_key) BETWEEN 8 AND 128),
  request_hash    text NOT NULL,
  status          text NOT NULL CONSTRAINT ck_idem_status CHECK (status IN ('IN_PROGRESS','COMPLETED')),
  response_status smallint,
  response_body   jsonb,
  created_at      timestamptz NOT NULL,
  expires_at      timestamptz NOT NULL,
  PRIMARY KEY (scope, idem_key)
);

CREATE TABLE outbox_events (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  aggregate_type text NOT NULL,
  aggregate_id   text NOT NULL,
  event_type     text NOT NULL,
  payload        jsonb NOT NULL,
  correlation_id text NOT NULL,
  created_at     timestamptz NOT NULL,
  published_at   timestamptz
);
CREATE INDEX ix_outbox_unpublished ON outbox_events(id) WHERE published_at IS NULL;
